// Writes coding/groups.ts, the server-safe catalog of the coding-test groups.
// The registry (coding/problems) imports react-dom/client and the starter code,
// so server pages and actions read this generated list instead.
// Run after adding or renaming a group or question: npm run coding:groups
import { writeFileSync } from "node:fs";
import path from "node:path";
import { topics } from "@/coding/problems";

export function renderCatalog(): string {
  const groups = topics.flatMap((topic) =>
    topic.groups.map((group) => ({
      slug: group.slug,
      title: group.title,
      topic: topic.name,
      questions: group.questions.map((question) => question.name),
    })),
  );
  return `// Generated by scripts/coding-groups.ts from coding/problems. Do not edit: run npm run coding:groups.

export type CodingGroupInfo = { slug: string; title: string; topic: string; questions: readonly string[] };

export const CODING_GROUPS: readonly CodingGroupInfo[] = ${JSON.stringify(groups, null, 2)};

export const codingGroup = (slug: string): CodingGroupInfo | undefined =>
  CODING_GROUPS.find((group) => group.slug === slug);
`;
}

if (process.argv[1] && path.basename(process.argv[1]).startsWith("coding-groups")) {
  writeFileSync(path.join(process.cwd(), "coding", "groups.ts"), renderCatalog());
  console.log("Wrote coding/groups.ts");
}
